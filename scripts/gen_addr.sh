# Generate kmod/addr.h from the connected device.
#
#   scripts/gen_addr.sh [stock-module.ko]
#
# The optional argument is a stock .ko taken from the device; it is only used to
# read the "module_layout" crc that the running kernel expects.  If omitted the
# script pulls /system/lib/modules/ansi_cprng.ko itself.
#
# Requires: adb, awk, tr, python3 (or python) and root on the device
# (`adb root`, or a rooted shell).
set -e

ADB=${ADB:-adb}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT="$ROOT/kmod/addr.h"
KO=${1:-}

# In recovery the symbols belong to the recovery kernel, and the resulting
# addr.h would be silently wrong rather than obviously broken.  Output, not
# exit status: adb shell on this Android version always returns 0.
if [ -n "$($ADB shell 'getprop ro.twrp.version' 2>/dev/null | tr -d '\r')" ]; then
	echo "running in recovery - kallsyms is the recovery kernel's; boot Android first" >&2
	exit 1
fi

PY=
for c in python3 python; do
	if command -v "$c" >/dev/null 2>&1; then PY=$c; break; fi
done
[ -n "$PY" ] || { echo "python3 not found" >&2; exit 1; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

$ADB shell 'cat /proc/kallsyms' | tr -d '\r' > "$TMP/kallsyms"
[ -s "$TMP/kallsyms" ] || { echo "could not read /proc/kallsyms" >&2; exit 1; }

sym() {
	v=$(awk -v n="$1" '$3 == n { print $1; exit }' "$TMP/kallsyms")
	case "$v" in
	""|00000000*)
		echo "symbol '$1' unavailable - kallsyms is returning zeroes." >&2
		echo "  Magisk   : adb shell 'su -c \"echo 0 > /proc/sys/kernel/kptr_restrict\"'" >&2
		echo "  userdebug: adb root && adb shell 'echo 0 > /proc/sys/kernel/kptr_restrict'" >&2
		exit 1
		;;
	esac
	printf '0x%sUL' "$v"
}

# Resolved before anything is written: a symbol that comes back as zero must not
# leave a half-filled addr.h behind for the next build to pick up.
A_REGULATOR_GET=$(sym regulator_get)
A_DEV_GET_DRVDATA=$(sym dev_get_drvdata)
A_MMC_DETECT_CHANGE=$(sym mmc_detect_change)
A_PRINTK=$(sym printk)
A_MSLEEP=$(sym msleep)

if [ -z "$KO" ]; then
	KO="$TMP/stock.ko"
	$ADB pull //system/lib/modules/ansi_cprng.ko "$KO" >/dev/null 2>&1 || true
fi
[ -s "$KO" ] || { echo "need a stock .ko to read module_layout crc" >&2; exit 1; }
CRC=$("$PY" "$ROOT/scripts/get_module_layout_crc.py" "$KO")

cat > "$OUT" <<EOF
/* Generated by scripts/gen_addr.sh - do not edit.
 * Kernel: $($ADB shell 'cat /proc/version' | tr -d '\r')
 */
#define A_REGULATOR_GET      $A_REGULATOR_GET
#define A_DEV_GET_DRVDATA    $A_DEV_GET_DRVDATA
#define A_MMC_DETECT_CHANGE  $A_MMC_DETECT_CHANGE
#define A_PRINTK             $A_PRINTK
#define A_MSLEEP             $A_MSLEEP

#define A_MODULE_LAYOUT_CRC  $CRC
EOF

echo "wrote $OUT"
cat "$OUT"
